use crate::crypto::keypair::AuthorityKeypair;
use crate::crypto::payload::CanonicalPayload;
use crate::domain::member::Member;
use crate::domain::record::CertificateRecord;
use base64::engine::general_purpose::STANDARD as BASE64;
use base64::Engine;
use chrono::Utc;
use rivide::crypto::Sha3;
use rivide::dsa::MlDsa65;

pub struct CertificateSigner;

impl CertificateSigner {
    pub fn sign_member(
        member: &Member,
        index: usize,
        authority: &AuthorityKeypair,
    ) -> Result<CertificateRecord, Box<dyn std::error::Error>> {
        let member_num = format!("{:04}", index + 1);
        let date_str = member
            .date
            .as_deref()
            .unwrap_or("2026-11-22");

        let seed_payload = CanonicalPayload::seed_payload(
            &member_num,
            &member.name,
            date_str,
            &authority.fingerprint,
        );

        let seed_sig = MlDsa65::sign(seed_payload.as_bytes(), &authority.secret_key)?;
        let seed_hash_bytes = Sha3::sha3_256(seed_sig.as_bytes());
        let seed_hash = hex::encode(seed_hash_bytes).to_uppercase();

        let short_checksum = &seed_hash[0..4];
        let cred_id = format!("RVD-DEV-{}-{}", member_num, short_checksum);
        let legality_id = format!(
            "RVD-65:{}-{}-{}",
            &seed_hash[0..4],
            &seed_hash[4..8],
            &seed_hash[8..12]
        );

        let signatory_name = "Moh. Ananda Firmansyah putra";
        let signatory_role = "Founder & Owner";

        let final_payload = CanonicalPayload::final_payload(
            &cred_id,
            &member.name,
            date_str,
            &legality_id,
            signatory_name,
            signatory_role,
        );

        let final_sig = MlDsa65::sign(final_payload.as_bytes(), &authority.secret_key)?;
        let is_valid = MlDsa65::verify(&final_sig, final_payload.as_bytes(), &authority.public_key);
        if !is_valid {
            return Err(format!("Critical: Self verification failed for {}", cred_id).into());
        }

        let final_sig_hash_bytes = Sha3::sha3_256(final_sig.as_bytes());
        let final_sig_hash = hex::encode(final_sig_hash_bytes).to_uppercase();
        let sig_base64 = BASE64.encode(final_sig.as_bytes());

        Ok(CertificateRecord {
            id: cred_id,
            member_no: index + 1,
            name: member.name.clone(),
            date: date_str.to_string(),
            legality_id,
            credit: "Generated by Rivide (NIST FIPS 204 ML-DSA-65)".to_string(),
            algorithm: authority.algorithm.clone(),
            key_fingerprint: authority.fingerprint.clone(),
            canonical_payload: final_payload,
            signature_sha3_256: final_sig_hash,
            signature_base64: sig_base64,
            issued_at: Utc::now().to_rfc3339(),
            status: "AUTHENTIC & VERIFIED".to_string(),
        })
    }
}
