use dev_credentials::domain::{CertificateConfig, CertificateRecord, Member, Signatory};

#[test]
fn test_member_serialization_roundtrip() {
    let member = Member {
        id: "RVD-DEV-0001-A334".to_string(),
        name: "Moh. Ananda Firmansyah Putra".to_string(),
        date: Some("2026-11-22".to_string()),
        legality_id: Some("RVD-65:A334-D9AA-A280".to_string()),
        member_no: Some(1),
        algorithm: Some("NIST FIPS 204 ML-DSA-65".to_string()),
        signature_sha3_256: Some("HASH123".to_string()),
        status: Some("AUTHENTIC & VERIFIED".to_string()),
    };

    let serialized = serde_json::to_string(&member).unwrap();
    let deserialized: Member = serde_json::from_str(&serialized).unwrap();
    assert_eq!(member, deserialized);
}

#[test]
fn test_config_defaults() {
    let config = CertificateConfig::default();
    assert_eq!(config.circle_name, "dev :");
    assert_eq!(config.circle_tagline, "OFFICIAL COMMUNITY");
    assert_eq!(config.default_certificate_title, "CERTIFICATE OF MEMBERSHIP");
    assert_eq!(config.default_subtitle, "THIS IS PROUDLY PRESENTED TO");
    assert_eq!(config.issue_date, "2026-11-22");
    assert_eq!(config.status, "OFFICIAL & VERIFIED");
    assert_eq!(config.signatories.len(), 3);
}

#[test]
fn test_signatory_equality() {
    let s1 = Signatory {
        name: "Test Name".to_string(),
        role: "Test Role".to_string(),
    };
    let s2 = Signatory {
        name: "Test Name".to_string(),
        role: "Test Role".to_string(),
    };
    assert_eq!(s1, s2);
}

#[test]
fn test_record_serialization() {
    let record = CertificateRecord {
        id: "RVD-DEV-0001-A334".to_string(),
        member_no: 1,
        name: "Alice".to_string(),
        date: "2026-11-22".to_string(),
        legality_id: "RVD-65:A334-D9AA-A280".to_string(),
        credit: "Generated by Rivide".to_string(),
        algorithm: "NIST FIPS 204 ML-DSA-65".to_string(),
        key_fingerprint: "PK-MLDSA65-1234".to_string(),
        canonical_payload: "org:dev:|cred_id:RVD-DEV-0001-A334".to_string(),
        signature_sha3_256: "SIG_HASH".to_string(),
        signature_base64: "SIG_B64".to_string(),
        issued_at: "2026-11-22T00:00:00Z".to_string(),
        status: "AUTHENTIC & VERIFIED".to_string(),
    };

    let serialized = serde_json::to_string(&record).unwrap();
    let deserialized: CertificateRecord = serde_json::from_str(&serialized).unwrap();
    assert_eq!(record, deserialized);
}
